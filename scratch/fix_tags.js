const tagsToFix = rawInput.split('\n').map(t => t.trim()).filter(t => t.length > 0);

function processFile(file) {
  let content = fs.readFileSync(file, 'utf8');
  let lines = content.split('\n');
  let modified = false;
  
  for (let i = 0; i < lines.length; i++) {
    for (const tag of tagsToFix) {
      if (lines[i].includes(`"${tag}"`) || lines[i].includes(`'${tag}'`) || lines[i].includes(`\`${tag}\``)) {
        if (!lines[i].trim().startsWith('//')) {
          lines[i] = `// [PERFORMANCE FIX] ${lines[i]}`;
          modified = true;
        }
      }
    }
  }
  
  if (modified) {
    fs.writeFileSync(file, lines.join('\n'));
    console.log(`Updated ${file}`);
  }
}

const files = ['app/lib/engine.ts', 'app/lib/engineNAR.ts'];
for (const file of files) {
  if (fs.existsSync(file)) {
    processFile(file);
  }
}
