import numpy as np

def calculate_kasamatsu_physical_score(
    row, race_num=1, distance=1400, surface='ダ',
    trainer_wins_today=0, model_dir=None
):
    """
    笠松競馬場 物理スコア計算（笠松特化パッチ適用版）
    主要バイアス:
      - 右回り・1周1181mの小回り平坦コース。圧倒的な「前残り（逃げ・先行有利）」馬場。
      - コーナーがきつく、スピードに乗ったまま回れるかが鍵。
      - 高齢馬（7歳以上）は笠松のスピード勝負についていけないことが多い。
      - 筒井勇騎手など、着実にヒモ（2〜3着）に持ってくる職人騎手が存在する。
    """
    score = 50.0

    # 特徴量取得
    age           = int(row.get('年齢', 4))
    pop           = int(row.get('人気', 10))
    odds          = float(row.get('単勝オッズ', 50.0))
    corner_pos    = float(row.get('4角番手', 99.0))
    prev_corner1  = float(row.get('前走1角番手', 99.0))
    jockey        = str(row.get('騎手', ''))

    # --- 1. 🌟 笠松特注: 馬券圏内への安定感抜群の筒井勇騎手(2〜3着付け推奨) ---
    # アタマ（1着）まで突き抜けるかは馬次第だが、2〜3着へのエスコートが非常に上手い。
    if '筒井' in jockey:
        score += 8.0 # ヒモ軸として信頼度大

    # --- 2. ❌ 笠松減点: スピード負けしやすい7歳以上の高齢馬 ---
    # 平坦でスピードが要求される笠松において、ズブくなった高齢馬はテンについていけず致命傷になる。
    if age >= 7:
        score -= 10.0

    # --- 3. 🌟 笠松特注: ヒモ荒れを演出する中穴候補(4〜7番人気必須) ---
    # 笠松は1番人気が飛ぶと一気に波乱になるが、その際に2〜3着に突っ込んでくるのがこの価格帯。
    if 4 <= pop <= 7:
        if prev_corner1 <= 4:
            # 前に行ける中穴馬は笠松では絶好の狙い目
            score += 7.0

    # --- 4. ❌ 笠松減点: 前残り馬場で届かない後方脚質(差し・追い込み) ---
    # コーナーがきつく直線が短い（236m）笠松で、4角時点で後方（6番手以降）にいる馬は物理的に届かない。
    if corner_pos >= 6 and corner_pos != 99.0:
        score -= 12.0
    elif prev_corner1 >= 6 and prev_corner1 != 99.0:
        # 前走でもテンに行けなかった馬は笠松で位置を取るのは厳しい
        score -= 8.0

    # --- 5. 🎯堅実フェーズ ＆ ⚠️波乱フェーズ ロジック（オッズ依存） ---
    # 笠松の1番人気がオッズ1.5倍以下の場合は「堅実フェーズ」として順当に信頼（逆らわない）。
    # 逆に1番人気のオッズが3.0倍以上の場合は「波乱フェーズ（1番人気過信禁物）」として評価を下げる。
    if pop == 1:
        if odds <= 1.5:
            score += 10.0 # 堅実フェーズ：逆らわずアタマ固定推奨
        elif odds >= 3.0:
            score -= 8.0 # 波乱フェーズ：1番人気の信頼度低下（大波乱の使者）

    # 基本的な逃げ・先行ボーナス（笠松特有）
    if prev_corner1 <= 2:
        score += 5.0

    # スコアのクリッピング（0〜100）
    score = max(0.0, min(100.0, score))

    return score
